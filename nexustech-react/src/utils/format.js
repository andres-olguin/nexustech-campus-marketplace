const clp = new Intl.NumberFormat('es-CL', { style: 'currency', currency: 'CLP', maximumFractionDigits: 0 });
const usd = new Intl.NumberFormat('es-CL', { style: 'currency', currency: 'USD', currencyDisplay: 'code', maximumFractionDigits: 2 });
const decimal = new Intl.NumberFormat('es-CL', { maximumFractionDigits: 2 });
const dateCL = new Intl.DateTimeFormat('es-CL', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'America/Santiago' });
export const formatCLP = (amount) => clp.format(amount);
export const formatUSD = (amount) => usd.format(amount);
export const formatNumber = (amount) => decimal.format(amount);
export const normalize = (text) => String(text).normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLocaleLowerCase('es');
export const formatDate = (date) => dateCL.format(new Date(date));
export const categories = ['Workstations', 'Hardware', 'Periféricos', 'Soluciones'];
export const finishes = ['Gris Espacial', 'Negro Mate', 'Plata Titanio'];
export const isEmail = (value) => /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value.trim());
